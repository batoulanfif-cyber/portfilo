const MAX_IMG_SIZE = 700000;
let cachedProjects = [];

function getProjects() {
  return cachedProjects;
}

async function loadProjects() {
  try {
    const res = await fetch('get_projects.php');
    const json = await res.json();
    if (json && json.ok && Array.isArray(json.projects)) {
      cachedProjects = json.projects;
    } else {
      cachedProjects = [];
    }
  } catch (e) {
    cachedProjects = [];
  }
}

async function saveProjectToServer(project) {
  const res = await fetch('save_project.php', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(project)
  });
  return await res.json();
}

async function deleteProjectFromServer(id) {
  const res = await fetch('delete_project.php', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ id: id })
  });
  return await res.json();
}

function currentLang() {
  return localStorage.getItem(STORAGE_KEY) || DEFAULT_LANG;
}

function esc(str) {
  return String(str == null ? '' : str).replace(/[&<>"']/g, c => (
    { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]
  ));
}

function buildTechHtml(techArr) {
  if (!Array.isArray(techArr) || techArr.length === 0) return '';
  return '<div class="project-tech">' +
    techArr.map(t => '<span>' + esc(t) + '</span>').join('') +
    '</div>';
}

function buildCard(p) {
  let media;
  if (p.image) {
    media = '<img src="' + esc(p.image) + '" alt="' + esc(p.title) + '" class="project-img">';
  } else {
    const placeholderClass = p.placeholderClass || 'placeholder-tech';
    const icon = p.icon || 'fas fa-code';
    media = '<div class="project-placeholder ' + placeholderClass + '"><i class="' + icon + '"></i></div>';
  }

  const linkHref = (p.link && p.link.trim()) ? esc(p.link) : '#';
  const viewText = translations[currentLang()].project_view || 'Voir le projet';

  return '' +
    '<div class="project-card">' +
      '<div class="project-image">' + media + '</div>' +
      '<div class="project-info">' +
        '<h3>' + esc(p.title) + '</h3>' +
        (p.desc ? '<p>' + esc(p.desc) + '</p>' : '') +
        buildTechHtml(p.tech) +
        '<div class="project-links">' +
          '<a href="' + linkHref + '" class="btn btn-sm btn-primary" target="_blank" rel="noopener"><i class="fas fa-external-link-alt"></i> ' + esc(viewText) + '</a>' +
        '</div>' +
      '</div>' +
    '</div>';
}

function renderProjects() {
  const grid = document.getElementById('projectsGrid');
  if (!grid) return;
  const projects = getProjects();
  grid.innerHTML = projects.map(buildCard).join('');

  grid.querySelectorAll('.project-card').forEach(card => {
    card.classList.add('animate-on-scroll');
    card.style.opacity = '1';
    card.style.transform = 'translateY(0)';
  });
}

function renderAdminList() {
  const list = document.getElementById('adminList');
  if (!list) return;
  const projects = getProjects();
  const lang = currentLang();

  if (projects.length === 0) {
    list.innerHTML = '<p class="admin-empty">' + esc(translations[lang].admin_no_projects) + '</p>';
    return;
  }

  list.innerHTML = projects.map(p => {
    const thumb = p.image
      ? '<img src="' + esc(p.image) + '" alt="">'
      : '<i class="' + (p.icon || 'fas fa-code') + '"></i>';
    return '' +
      '<div class="admin-item">' +
        '<div class="admin-item-thumb">' + thumb + '</div>' +
        '<div class="admin-item-info">' +
          '<strong>' + esc(p.title) + '</strong>' +
          (p.link ? '<span class="admin-item-link">' + esc(p.link) + '</span>' : '') +
        '</div>' +
        '<div class="admin-item-actions">' +
          '<button type="button" class="admin-item-btn admin-item-edit" data-id="' + esc(p.id) + '"><i class="fas fa-pen"></i> ' + esc(translations[lang].admin_edit) + '</button>' +
          '<button type="button" class="admin-item-btn admin-item-del" data-id="' + esc(p.id) + '"><i class="fas fa-trash"></i> ' + esc(translations[lang].admin_delete) + '</button>' +
        '</div>' +
      '</div>';
  }).join('');

  list.querySelectorAll('.admin-item-edit').forEach(btn => {
    btn.addEventListener('click', () => openForm(getProjects().find(p => p.id === btn.dataset.id)));
  });
  list.querySelectorAll('.admin-item-del').forEach(btn => {
    btn.addEventListener('click', () => {
      const langNow = currentLang();
      if (!confirm(translations[langNow].admin_confirm_delete)) return;
      deleteProject(btn.dataset.id);
    });
  });
}

async function deleteProject(id) {
  try {
    const result = await deleteProjectFromServer(id);
    if (result && result.ok) {
      await loadProjects();
      renderProjects();
      renderAdminList();
    } else if (result && result.error === 'unauthorized') {
      handleUnauthorized();
    } else {
      alert('Échec de la suppression du projet' + (result && result.error ? ' (' + result.error + ')' : '') + '. Veuillez réessayer.');
    }
  } catch (e) {
    alert('Erreur réseau : impossible de supprimer le projet. Veuillez réessayer.');
  }
}

let editId = null;
let editIcon = 'fas fa-code';
let editPlaceholderClass = 'placeholder-tech';
let currentImage = null;

function openOverlay(el) {
  el.classList.add('active');
  document.body.style.overflow = 'hidden';
}

function closeOverlay(el) {
  el.classList.remove('active');
  document.body.style.overflow = '';
}

function openForm(project) {
  editId = project ? project.id : null;
  editIcon = (project && project.icon) ? project.icon : 'fas fa-code';
  editPlaceholderClass = (project && project.placeholderClass) ? project.placeholderClass : 'placeholder-tech';
  currentImage = null;
  document.getElementById('pfTitle').value = project ? project.title : '';
  document.getElementById('pfLink').value = project ? (project.link || '') : '';
  document.getElementById('pfDesc').value = project ? (project.desc || '') : '';
  document.getElementById('pfTech').value = project ? (project.tech || []).join(', ') : '';
  document.getElementById('pfImage').value = '';
  const preview = document.getElementById('adminImagePreview');
  preview.innerHTML = '';
  document.getElementById('adminFormTitle').textContent =
    translations[currentLang()][project ? 'admin_edit_title' : 'admin_form_title'] || 'Add project';
  openOverlay(document.getElementById('adminFormOverlay'));
}

const formStatusClass = 'form-status';
let serverAuthed = false;

function fetchJson(url, opts) {
  return fetch(url, opts).then(res => res.json());
}

function isAuthed() {
  return serverAuthed;
}

function openAdminPanel() {
  const lang = currentLang();
  const overlay = document.getElementById('adminOverlay');
  document.getElementById('adminTitle').textContent =
    translations[lang].admin_title;
  overlay.classList.add('admin-modal-wide');
  renderAdminList();
  showAdminTab('projects');
  refreshMessages();
  openOverlay(overlay);
}

function showAdminTab(tab) {
  document.querySelectorAll('.admin-tab-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.tab === tab);
  });
  document.getElementById('adminProjectsPanel').style.display =
    tab === 'projects' ? '' : 'none';
  document.getElementById('adminMessagesPanel').style.display =
    tab === 'messages' ? '' : 'none';
  if (tab === 'messages') refreshMessages();
}

function renderMessages(messages) {
  const list = document.getElementById('messagesList');
  if (!list) return;
  const lang = currentLang();

  if (!messages || messages.length === 0) {
    list.innerHTML = '<p class="admin-empty">' + esc(translations[lang].messages_empty) + '</p>';
    return;
  }

  list.innerHTML = messages.map(m => {
    const safeName = esc(m.name || '');
    const safeEmail = esc(m.email || '');
    const safeMsg = esc(m.message || '');
    const safeDate = esc(m.date || '');
    const safeTime = esc(m.time || '');
    const safeId = esc(m.id || '');
    return '' +
      '<div class="admin-message" data-id="' + safeId + '">' +
        '<div class="admin-message-head">' +
          '<div class="admin-msg-person">' +
            '<div class="admin-msg-avatar"><i class="fas fa-user"></i></div>' +
            '<div class="admin-msg-id">' +
              '<strong>' + safeName + '</strong>' +
              '<a class="admin-msg-mail" href="mailto:' + safeEmail + '">' + safeEmail + '</a>' +
            '</div>' +
          '</div>' +
          '<div class="admin-msg-date">' +
            '<i class="fas fa-calendar-alt"></i> ' + safeDate +
            ' &nbsp;<i class="fas fa-clock"></i> ' + safeTime +
          '</div>' +
        '</div>' +
        '<div class="admin-msg-body">' + safeMsg + '</div>' +
        '<div class="admin-msg-foot">' +
          '<button type="button" class="admin-item-btn admin-item-del admin-msg-del" data-id="' + safeId + '">' +
            '<i class="fas fa-trash"></i> ' + esc(translations[lang].admin_delete) +
          '</button>' +
        '</div>' +
      '</div>';
  }).join('');

  list.querySelectorAll('.admin-msg-del').forEach(btn => {
    btn.addEventListener('click', () => deleteMessage(btn.dataset.id, btn));
  });
}

async function refreshMessages() {
  const badge = document.getElementById('messagesBadge');
  const list = document.getElementById('messagesList');
  const lang = currentLang();
  try {
    const json = await fetchJson('get_messages.php', { method: 'POST' });
    if (!json || json.ok === false) {
      if (json && json.error === 'unauthorized') {
        handleUnauthorized();
      }
      return;
    }
    const messages = (json.messages || []).sort((a, b) => {
      const da = new Date((a.datetime || a.date || '')).getTime() || 0;
      const db = new Date((b.datetime || b.date || '')).getTime() || 0;
      return db - da;
    });
    if (badge) badge.textContent = messages.length;
    renderMessages(messages);
  } catch (err) {
    if (list) list.innerHTML = '<p class="admin-empty">' + esc(translations[lang].messages_delete_error) + '</p>';
  }
}

async function deleteMessage(id, btn) {
  const lang = currentLang();
  if (!confirm(translations[lang].messages_delete_confirm)) return;
  try {
    const json = await fetchJson('delete_message.php', {
      method: 'POST',
      headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
      body: 'id=' + encodeURIComponent(id)
    });
    if (json && json.ok) {
      refreshMessages();
    } else if (json && json.error === 'unauthorized') {
      handleUnauthorized();
    } else {
      alert(translations[lang].messages_delete_error);
    }
  } catch (err) {
    alert(translations[lang].messages_delete_error);
  }
}

function handleUnauthorized() {
  const lang = currentLang();
  serverAuthed = false;
  closeOverlay(document.getElementById('adminOverlay'));
  document.getElementById('loginError').style.display = 'none';
  const oldErr = document.getElementById('loginError');
  oldErr.style.display = 'block';
  openOverlay(document.getElementById('loginOverlay'));
  alert(translations[lang].admin_session_expired);
}

function bindAdmin() {
  const overlay = document.getElementById('adminOverlay');
  const formOverlay = document.getElementById('adminFormOverlay');
  const loginOverlay = document.getElementById('loginOverlay');

  document.getElementById('adminCloseBtn').addEventListener('click', () => closeOverlay(overlay));
  overlay.addEventListener('click', (e) => { if (e.target === overlay) closeOverlay(overlay); });

  document.getElementById('adminAddBtn').addEventListener('click', () => openForm(null));

  document.getElementById('adminFormCloseBtn').addEventListener('click', () => closeOverlay(formOverlay));
  document.getElementById('adminFormCancelBtn').addEventListener('click', () => closeOverlay(formOverlay));
  formOverlay.addEventListener('click', (e) => { if (e.target === formOverlay) closeOverlay(formOverlay); });

  document.getElementById('loginForm').addEventListener('submit', async (e) => {
    e.preventDefault();
    const user = document.getElementById('loginUser').value.trim();
    const pass = document.getElementById('loginPass').value;
    const errEl = document.getElementById('loginError');
    errEl.style.display = 'none';

    const data = new FormData();
    data.append('username', user);
    data.append('password', pass);

    try {
      const res = await fetch('login.php', { method: 'POST', body: data });
      const json = await res.json();
      if (json && json.ok) {
        serverAuthed = true;
        document.getElementById('loginPass').value = '';
        document.getElementById('loginUser').value = '';
        closeOverlay(loginOverlay);
        openAdminPanel();
      } else {
        errEl.style.display = 'block';
      }
    } catch (err) {
      errEl.style.display = 'block';
    }
  });

  document.querySelectorAll('.admin-tab-btn').forEach(btn => {
    btn.addEventListener('click', () => showAdminTab(btn.dataset.tab));
  });

  const refreshBtn = document.getElementById('adminRefreshBtn');
  if (refreshBtn) refreshBtn.addEventListener('click', refreshMessages);

  document.getElementById('loginCloseBtn').addEventListener('click', () => closeOverlay(loginOverlay));
  loginOverlay.addEventListener('click', (e) => { if (e.target === loginOverlay) closeOverlay(loginOverlay); });

  const imgInput = document.getElementById('pfImage');
  const preview = document.getElementById('adminImagePreview');

  imgInput.addEventListener('change', () => {
    const file = imgInput.files[0];
    currentImage = null;
    preview.innerHTML = '';
    if (!file) return;
    if (!file.type.startsWith('image/')) { alert('Veuillez choisir une image.'); return; }
    if (file.size > MAX_IMG_SIZE) { alert('Image trop lourde (max ~700 Ko).'); imgInput.value = ''; return; }
    const reader = new FileReader();
    reader.onload = (e) => {
      currentImage = e.target.result;
      preview.innerHTML = '<img src="' + currentImage + '" alt="aperçu">';
    };
    reader.readAsDataURL(file);
  });

  document.getElementById('adminForm').addEventListener('submit', async (e) => {
    e.preventDefault();
    if (!isAuthed()) return;
    const title = document.getElementById('pfTitle').value.trim();
    if (!title) return;
    const link = document.getElementById('pfLink').value.trim();
    const desc = document.getElementById('pfDesc').value.trim();
    const tech = document.getElementById('pfTech').value
      .split(',')
      .map(t => t.trim())
      .filter(Boolean);

    const projectData = {
      title: title,
      link: link,
      desc: desc,
      tech: tech,
      image: currentImage,
      icon: editIcon,
      placeholderClass: editPlaceholderClass
    };

    if (editId) {
      projectData.id = editId;
    }

    try {
      const result = await saveProjectToServer(projectData);
      if (result && result.ok) {
        await loadProjects();
        renderProjects();
        renderAdminList();
        closeOverlay(formOverlay);
      } else if (result && result.error === 'unauthorized') {
        handleUnauthorized();
      } else {
        alert('Échec de l\'enregistrement du projet' + (result && result.error ? ' (' + result.error + ')' : '') + '. Veuillez réessayer.');
      }
    } catch (err) {
      alert('Erreur réseau : impossible d\'enregistrer le projet. Veuillez réessayer.');
    }
  });
}

window.addEventListener('load', function initProjects() {
  window.removeEventListener('load', initProjects);
  loadProjects().then(() => {
    renderProjects();
    bindAdmin();

    if (window.location.hash === '#admin') {
      document.getElementById('loginError').style.display = 'none';
      openOverlay(document.getElementById('loginOverlay'));
      window.location.hash = '';
    }
  });
});

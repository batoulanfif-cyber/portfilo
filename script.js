const STORAGE_KEY = 'dev-by-ferdaous-lang';
const DEFAULT_LANG = 'fr';
const farsiFonts = {
  ar: "'Tajawal','Inter',sans-serif"
};

function applyLanguage(lang) {
  const langData = translations[lang];
  if (!langData) return;

  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');

  const html = document.documentElement;
  if (lang === 'ar') {
    html.style.setProperty('--font-primary', farsiFonts.ar);
    html.classList.add('rtl');
  } else {
    html.style.removeProperty('--font-primary');
    html.classList.remove('rtl');
  }

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (langData[key]) {
      el.innerHTML = langData[key];
    }
  });

  const navToggle = document.getElementById('navToggle');
  const langNames = { fr: "Menu de navigation", en: "Navigation menu", ar: "قائمة التنقل" };
  navToggle.setAttribute('aria-label', langNames[lang]);
  navToggle.setAttribute('title', langNames[lang]);

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  document.title = lang === 'fr'
    ? 'Dev by Ferdaous | Portfolio Développeuse Web'
    : lang === 'en'
      ? 'Dev by Ferdaous | Web Developer Portfolio'
      : 'Dev by Ferdaous | صفحة مطورة ويب';

  localStorage.setItem(STORAGE_KEY, lang);
}

document.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem(STORAGE_KEY) || DEFAULT_LANG;
  const valid = translations[savedLang] ? savedLang : DEFAULT_LANG;
  applyLanguage(valid);

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      const lang = btn.dataset.lang;
      applyLanguage(lang);
      document.querySelectorAll('.lang-btn').forEach(b => b.classList.toggle('active', b.dataset.lang === lang));
      if (typeof renderProjects === 'function' && document.getElementById('projectsGrid')) {
        renderProjects();
      }
    });
  });

  const navbar = document.getElementById('navbar');
  const navToggle = document.getElementById('navToggle');
  const navMenu = document.getElementById('navMenu');
  const navLinks = document.querySelectorAll('.nav-link');

  window.addEventListener('scroll', () => {
    navbar.classList.toggle('scrolled', window.scrollY > 50);
  });

  navToggle.addEventListener('click', () => {
    navToggle.classList.toggle('active');
    navMenu.classList.toggle('active');
  });

  navLinks.forEach(link => {
    link.addEventListener('click', () => {
      navToggle.classList.remove('active');
      navMenu.classList.remove('active');
    });
  });

  const observerOptions = { threshold: 0.15, rootMargin: '0px 0px -50px 0px' };
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('visible');
        observer.unobserve(entry.target);
      }
    });
  }, observerOptions);

  const animateElements = document.querySelectorAll(
    '.section-header, .about-intro, .about-text p:not(.about-intro), .stat-item, .skill-card, .project-card, .service-card, .contact-info, .contact-form'
  );

  animateElements.forEach(el => {
    el.classList.add('animate-on-scroll');
    observer.observe(el);
  });

  const contactForm = document.getElementById('contactForm');
  if (contactForm) {
    contactForm.addEventListener('submit', async (e) => {
      e.preventDefault();
      const t = translations[currentLang()];
      const submitBtn = contactForm.querySelector('.btn-submit span');
      const name = document.getElementById('name').value.trim();
      const email = document.getElementById('email').value.trim();
      const message = document.getElementById('message').value.trim();

      const errP = contactForm.querySelector('.form-status');
      if (errP) errP.remove();

      const fail = (txt) => {
        const p = document.createElement('p');
        p.className = formStatusClass + ' form-error';
        p.textContent = txt;
        contactForm.appendChild(p);
      };

      if (!name) { fail(t.form_error_name); return; }
      if (!email || !/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(email)) { fail(t.form_error_email); return; }
      if (!message) { fail(t.form_error_message); return; }

      submitBtn.textContent = t.form_sending;
      const data = new FormData();
      data.append('name', name);
      data.append('email', email);
      data.append('message', message);

      try {
        const res = await fetch('save_message.php', { method: 'POST', body: data });
        const json = await res.json();
        if (json && json.ok) {
          submitBtn.textContent = t.form_sent;
          contactForm.reset();
          setTimeout(() => { submitBtn.textContent = t.form_submit; }, 3000);
        } else {
          submitBtn.textContent = t.form_submit;
          if (errP) errP.remove();
          const p = document.createElement('p');
          p.className = formStatusClass + ' form-error';
          p.textContent = t.form_failed;
          contactForm.appendChild(p);
        }
      } catch (err) {
        submitBtn.textContent = t.form_submit;
        fail(t.form_failed);
      }
    });
  }

  document.querySelectorAll('a[href^="#"]').forEach(anchor => {
    anchor.addEventListener('click', function(e) {
      e.preventDefault();
      const target = document.querySelector(this.getAttribute('href'));
      if (target) target.scrollIntoView({ behavior: 'smooth' });
    });
  });
});

